export const getServiceVideo = (slug) => {
  for (const category of serviceVideos) {
    const service = category.services.find(s => s.slug === slug);
    if (service) return service;
  }
  return null;
};

export const getServicesByCategory = (categoryName) => {
  const category = serviceVideos.find(c => c.category === categoryName);
  return category ? category.services : [];
};

export const getAllServiceSlugs = () => {
  const slugs = [];
  for (const category of serviceVideos) {
    for (const service of category.services) {
      slugs.push({ slug: service.slug, category: category.category, service_name: service.service_name });
    }
  }
  return slugs;
};